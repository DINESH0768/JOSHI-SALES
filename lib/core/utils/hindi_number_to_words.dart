String _convertUnderHundred(int n) {
  if (n < 0 || n >= 100) return '';
  return _units[n];
}

String hindiNumberToWords(int number) {
  if (number == 0) {
    return 'शून्य रुपये मात्र';
  }

  int n = number.abs();
  List<String> parts = [];

  // Lakhs (1,00,000)
  if (n >= 100000) {
    int lakhs = n ~/ 100000;
    n %= 100000;
    parts.add('${_convertUnderHundred(lakhs)} लाख');
  }

  // Thousands (1,000)
  if (n >= 1000) {
    int thousands = n ~/ 1000;
    n %= 1000;
    parts.add('${_convertUnderHundred(thousands)} हजार');
  }

  // Hundreds (100)
  if (n >= 100) {
    int hundreds = n ~/ 100;
    n %= 100;
    parts.add('${_convertUnderHundred(hundreds)} सौ');
  }

  // Remainder (< 100)
  if (n > 0) {
    parts.add(_convertUnderHundred(n));
  }

  String result = parts.join(' ').trim();
  return '$result रुपये मात्र';
}
